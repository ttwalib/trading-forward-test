#!/usr/bin/env python3
"""Prints the CURRENT SPECIFICATION of the forward test from the repo's own configuration (added 2026-11-21).

One generated document instead of hand-edited summaries that drift: every number below is read from the code or data
files at the moment of the run. History lives in ops/runbook.md (CHANGES sections) and ops/preregistration.md
(amendment log); this file only says what is true now.

  python3 spec.py REPO [OUTFILE]        (the nightly maths on GitHub writes ops/SPEC.md every night)
"""
import json, os, subprocess, sys, datetime as dt

HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import tcal, allocator as A, library as L, checks


def git(repo, *a):
    try: return subprocess.run(["git", "-C", repo] + list(a), capture_output=True, text=True).stdout.strip()
    except Exception: return ""


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows: out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


def tdays(a, b):
    n = 0; d = a
    while d <= b:
        if d.weekday() < 5 and d not in tcal.HOLIDAYS and d not in tcal.HALF: n += 1
        d += dt.timedelta(days=1)
    return n


def main(repo):
    u = json.load(open(os.path.join(repo, "data", "universe.json")))
    T = json.load(open(os.path.join(repo, "ops", "tasks.json")))
    lib = sorted(json.load(open(os.path.join(repo, "data", "library", "daily.json"))), key=lambda k: int(k.split()[0][1:]))
    S = A.sleeves(repo); tr = checks.trials(repo)
    hol = sorted(d.isoformat() for d in tcal.HOLIDAYS if tcal.START <= d <= tcal.SETTLE_END)
    half = sorted(d.isoformat() for d in tcal.HALF if tcal.START <= d <= tcal.SETTLE_END)
    P = []
    P.append("# Quantavius the 1st: current specification\n")
    P.append("Generated by `scripts/spec.py` on %s from commit `%s` (%s). Do not edit by hand: change the code or data and "
             "regenerate. What changed and why: `ops/runbook.md` (CHANGES) and `ops/preregistration.md` (amendment log).\n"
             % (dt.datetime.now(tcal.NY).strftime("%Y-%m-%d %H:%M ET"), git(repo, "rev-parse", "--short", "HEAD"), git(repo, "log", "-1", "--format=%cs")))
    P.append("Nothing is traded. Every result is simulated on real market prices. No script may contain an order call "
             "(`scripts/no_orders.py`). This is testing, not financial advice.\n")
    P.append("## Dates\n")
    P.append(table(["Item", "Value"], [
        ["Test (stocks and options)", "%s to %s" % (tcal.START, tcal.END)], ["Crypto", "to %s" % tcal.CRYPTO_END],
        ["Option settlement only", "to %s" % tcal.SETTLE_END],
        ["Verdict window (H1)", "%s to %s (%d full trading days)" % (tcal.ALLOC_FREEZE, tcal.END, tdays(tcal.ALLOC_FREEZE, tcal.END))],
        ["Interim reading (decides nothing)", "data to %s" % tcal.INTERIM_END],
        ["Frozen holdout", "%s to %s (%d full trading days)" % (tcal.HOLDOUT_START, tcal.END, tdays(tcal.HOLDOUT_START, tcal.END))],
        ["Scripts frozen from", str(tcal.ALLOC_FREEZE)], ["Final report", str(tcal.FINAL_REPORT)],
        ["Market holidays", ", ".join(hol)], ["Half days (no new entries)", ", ".join(half)]]) + "\n")
    P.append("## What is judged\n")
    P.append("Three separate hypotheses, never pooled (`ops/preregistration.md`): **H1** the AI's allocation against SPY, "
             "equal weight and baseline A (the verdict; `verdict_check` in the allocator report), **H2** the strategy lab, "
             "**H3** the agent picks against the random control list. If a simple rule beats both kinds of AI allocation, "
             "the AI reviews its strategies and declares a revised approach aimed at the highest return after costs; H1 is "
             "still judged on the frozen formula.\n")
    P.append("## Universe\n")
    P.append(table(["List", "Size", "Used for"], [
        ["Watchlist", len(u["watchlist"]), "Baseline A, variants, adaptive breakout, options O/D1/W4"],
        ["Control list (random, seed %s)" % u["seed"], len(u["control"]), "Same rules as baseline A: the benchmark for stock selection"],
        ["Liquid universe (today's S&P 100, survivorship-flattered)", len(u["universe"]), "Daily library strategies"],
        ["ETFs", len(u["etfs"]), "Index, sector, bond, gold, commodity and foreign-share sleeves"],
        ["Wide intraday universe", "on" if u.get("intraday_wide") else "off", "5-minute strategies on the whole universe (kept off)"]]) + "\n")
    P.append("Watchlist: %s\n\nControl list: %s\n" % (", ".join(u["watchlist"]), ", ".join(u["control"])))
    P.append("## Strategy sleeves (%d in the allocator today)\n" % len(S))
    P.append("Library (%d strategies, `scripts/library.py`, run nightly on stored bars): %s.\n" % (len(lib), "; ".join(lib)))
    P.append("Pairs: %s. Multi-asset trend: %s. Borrow fee for short legs: %s%% a year unless a daily borrow file exists. "
             "Intraday fills: implementable (fill lag %d bar; `fills.py`).\n"
             % (", ".join("%s/%s" % p for p in L.PAIRS), ", ".join(L.MULTI), L.BORROW_PCT_YR, L.FILL_LAG))
    P.append("Ledger sleeves (simulated live each day): %s.\n" % "; ".join(sorted(k for k in S if not k.startswith("L") or not k[1].isdigit())))
    P.append("## Allocator (`scripts/allocator.py`)\n")
    P.append(table(["Setting", "Value"], [
        ["Invested", "always 100%, no cash"], ["Rebalancing", "%s, no-trade band %.0f points" % (A.REBALANCE, A.BAND * 100)],
        ["Cap per sleeve", "%.0f%%" % (A.CAP * 100)],
        ["Cap for the short-premium option sleeves together (W1, W2, D2, D3)", "%.0f%%" % (A.GROUP_CAP * 100)],
        ["Sizing", "%.2f x Kelly with Ledoit-Wolf covariance over %d days, long only" % (A.KELLY, A.COV_WIN)],
        ["Evidence window", "%d days; a sleeve needs %d active days" % (A.WIN, A.MIN_DAYS)],
        ["Backtest days count for", "%.0f%% (%.0f%% for %s), at most %d day-equivalents" % (A.PRIOR_HAIR * 100, A.PRIOR_HAIR_SURV * 100, ", ".join(x.strip() for x in A.SURV_SLEEVES), A.PRIOR_EQ)],
        ["Drawdown breaker", "scaled to each sleeve's volatility (at least -4% over 10 days or 8% drawdown)"],
        ["Duplicates", "equal within %s on at least %d days on which both traded" % (A.DUP_TOL, A.DUP_DAYS)],
        ["Rival allocators (same rules and costs)", "risk parity, minimum variance, recent winners, AI judgment (weekly sealed weights)"],
        ["Benchmarks", "SPY, equal weight, baseline A; each also volatility-matched"]]) + "\n")
    P.append("## Frozen scripts (%d, from %s)\n" % (len(A.FROZEN_FILES), tcal.ALLOC_FREEZE))
    P.append(", ".join("`%s`" % f for f in A.FROZEN_FILES) + ". Hashes in `ops/freeze.json`; checked nightly and by the freeze-guard workflow.\n")
    P.append("## Scheduled AI tasks (New York time)\n")
    P.append(table(["Task", "When", "Model", "What it does"], [[t["name"], t["when"], t["model"], t["does"]] for t in T["tasks"]]) + "\n")
    per_day = "About 25 AI sessions on a trading day (8 crypto, 6 live decisions, 3 watchdog, 2 stocks, and one each of morning research, options, adaptive, evening scoring, orchestrator and ML nightly)."
    P.append(per_day + "\n")
    P.append("## Work done on GitHub with no AI in the loop\n")
    P.append(table(["Job", "When", "What it does"], [[t["name"], t["when"], t["does"]] for t in T["github"]]) + "\n")
    P.append("## Checks that run by themselves\n")
    P.append("Freeze guard; no-orders check; health line and alert issue (ticks, gaps, Actions minutes, token expiry); "
             "live-versus-replay parity with tolerances (entry %.1f%%, feature %.0f%%, day fails above %.0f%% of candidates); "
             "random past day re-run against the ledger every night; planted-leak test for the audit; cross-source price "
             "check; data-quality scan; trial ledger (%d unique trials logged so far).\n"
             % (checks.ENTRY_TOL * 100, checks.FEAT_TOL * 100, checks.FEAT_SHARE * 100, tr["unique_trials"]))
    P.append("## Known limits\n")
    P.append("Short window for small edges; simulated fills and estimated costs; today's index membership (survivorship: "
             "measured in `data/pit/report.json`); a fully invested, partly hedged book compared with unhedged SPY; "
             "option Greeks are estimates; one person owns the pinger token (expires %s)." % "2027-03-31")
    return "\n".join(P) + "\n"


if __name__ == "__main__":
    txt = main(sys.argv[1] if len(sys.argv) > 1 else ".")
    if len(sys.argv) > 2:
        with open(sys.argv[2], "w") as f: f.write(txt)
    else: sys.stdout.write(txt)
